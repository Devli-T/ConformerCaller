"""
ConformerCaller — Central Configuration
========================================
All paths, constants, and shared configuration for the ConformerCaller project.

DATA_ROOT should point to the directory holding the public HELIX01-04 data
(prepared with `python scripts/prepare_data.py --dest <DATA_ROOT>`):

    <DATA_ROOT>/
    ├── FAST5/                         extracted .fast5 files
    ├── Reference/completed_library.csv
    ├── HELIX01-04_master_db.txt       per-read motif labels
    └── processed/                     generated by the preprocessing scripts

Set the CONFORMERCALLER_DATA_ROOT environment variable (recommended) or
edit DATA_ROOT below. Defaults to ./data inside the repository.
"""

import os
from pathlib import Path
import torch


# ============================================================================
# Paths
# ============================================================================

# Workspace root (where code lives)
PROJECT_ROOT = Path(__file__).parent.resolve()

# Data root — set via environment variable or edit the default below
DATA_ROOT = Path(os.environ.get("CONFORMERCALLER_DATA_ROOT", PROJECT_ROOT / "data")).expanduser()

# Data paths
FAST5_DIR   = DATA_ROOT / "FAST5"
REFERENCE_DIR = DATA_ROOT / "Reference"
COMPLETED_LIBRARY_PATH = REFERENCE_DIR / "completed_library.csv"
MOTIF_DESIGN_PATH      = REFERENCE_DIR / "motif_design_sequences.csv"
ENCODED_CSV_PATH = DATA_ROOT / "HELIX01-04-encoded.csv"

# Per-read motif labels: public Zenodo name first, then the legacy CSV name
_master_db_candidates = [
    DATA_ROOT / "HELIX01-04_master_db.txt",
    DATA_ROOT / "master_db.txt",
    DATA_ROOT / "master_db.csv",
]
MASTER_DB_PATH = next((p for p in _master_db_candidates if p.exists()), _master_db_candidates[0])

# Output paths — preprocessed data and model checkpoints
PROCESSED_DATA_DIR = DATA_ROOT / "processed"
